//! Build `data/french.morph` from the Grammalecte lexicon of inflected
//! forms (<https://grammalecte.net>, MPL-2.0).
//!
//! ```sh
//! curl -LO https://grammalecte.net/dic/lexique-grammalecte-fr-v7.7.zip && unzip lexique-grammalecte-fr-v7.7.zip
//! cargo run --release --example build_french -- lexique-grammalecte-fr-v7.7.txt > data/french.morph
//! ```
//!
//! Each row gives a form, its lemma and Grammalecte tags (`v1_it_x__a ipre
//! spre 1sg 3sg`). They become UniMorph features (`V;IND;PRS;1;SG`, one row
//! per mood and person), and the paradigms are drafted from those tables
//! like any UniMorph language. Proper names are left out.

use std::collections::BTreeSet;
use std::process::ExitCode;

const HEADER: &str = "\
! =====================================================================
!  GENERATED by examples/build_french.rs: do not edit by hand.
!
!  The lexicon is derived from the Grammalecte French lexicon
!  (https://grammalecte.net), by Olivier R., licensed under the Mozilla
!  Public License 2.0. The notice is in data/french-GRAMMALECTE-LICENSE.txt;
!  the source is the lexique-grammalecte-fr zip on grammalecte.net.
! =====================================================================

";

/// Grammalecte's word-class tag → UniMorph part of speech.
fn pos(tags: &[&str]) -> Option<&'static str> {
    let first = *tags.first()?;
    if first.starts_with('v') {
        return Some("V");
    }
    Some(match first {
        "nom" => "N",
        "adj" => "ADJ",
        "adv" => "ADV",
        "loc.adv" => "ADV",
        "mg" => {
            // the second tag says the class: det, detpos, detdem, prep,
            // loc.prep, cjco, cjsub, proint, properobj, negadv, advint, ...
            let kind = tags.get(1).copied().unwrap_or("");
            let has = |t: &str| tags.contains(&t);
            if kind.starts_with("det") {
                "DET"
            } else if kind.contains("prep") {
                "ADP"
            } else if kind.starts_with("cj") || kind.starts_with("loc.cj") {
                "CONJ"
            } else if kind.starts_with("pro") {
                "PRO"
            } else if kind.contains("adv") || has("adv") {
                "ADV"
            } else if has("interj") {
                "INTJ"
            } else {
                return None;
            }
        }
        _ => return None,
    })
}

/// Mood/tense tags → UniMorph features.
fn mood(t: &str) -> Option<&'static str> {
    Some(match t {
        "infi" => "NFIN",
        "ppas" => "V.PTCP;PST",
        "ppre" => "V.PTCP;PRS",
        "ipre" => "IND;PRS",
        "iimp" => "IND;PST;IPFV",
        "ipsi" => "IND;PST;PFV",
        "ifut" => "IND;FUT",
        "cond" => "COND",
        "spre" => "SBJV;PRS",
        "simp" => "SBJV;PST",
        "impe" => "IMP",
        _ => return None,
    })
}

fn person(t: &str) -> Option<&'static str> {
    // `3pl!` marks the forms of être/avoir; the mark is Grammalecte's own
    Some(match t.trim_end_matches(['!', '?']) {
        "1sg" | "1isg" | "1jsg" => "1;SG",
        "2sg" => "2;SG",
        "3sg" => "3;SG",
        "1pl" => "1;PL",
        "2pl" => "2;PL",
        "3pl" => "3;PL",
        _ => return None,
    })
}

/// The UniMorph feature strings of one Grammalecte row (several when it
/// lists several moods or persons).
fn features(tags: &[&str]) -> Vec<String> {
    let Some(p) = pos(tags) else { return Vec::new() };
    let gender: Option<&str> = tags.iter().find_map(|t| match *t {
        "mas" => Some("MASC"),
        "fem" => Some("FEM"),
        _ => None,
    });
    let number: Vec<&str> = tags
        .iter()
        .filter_map(|t| match *t {
            "sg" => Some("SG"),
            "pl" => Some("PL"),
            _ => None,
        })
        .collect();
    let gn = |base: String| -> Vec<String> {
        let base = match gender {
            Some(g) => format!("{base};{g}"),
            None => base,
        };
        if number.is_empty() {
            vec![base]
        } else {
            number.iter().map(|n| format!("{base};{n}")).collect()
        }
    };
    if p != "V" {
        return gn(p.to_string());
    }
    let moods: Vec<&str> = tags.iter().filter_map(|t| mood(t)).collect();
    let persons: Vec<&str> = tags.iter().filter_map(|t| person(t)).collect();
    let mut out = Vec::new();
    for m in moods {
        if m.starts_with("V.PTCP;PST") {
            out.extend(gn(format!("V;{m}")));
        } else if persons.is_empty() || m == "NFIN" || m.starts_with("V.PTCP") {
            out.push(format!("V;{m}"));
        } else {
            out.extend(persons.iter().map(|ps| format!("V;{m};{ps}")));
        }
    }
    out
}

/// Elided clitics (l' d' j' qu' ...) before a word starting with a vowel
/// or h; the generated `Root` becomes `Words`.
const CLITICS: &str = "\
OPTION apostrophe_in_words true
CLASS VH = a e i o u y à â é è ê ë î ï ô ù û ü h

LEXICON Root
  0 Clitics ;
  0 Host ;

LEXICON Host
  0 Suppletive ;
  0 Words ;

LEXICON Clitics
  l':le      DET    Host  @next=VH ;
  l':le      PRO    Host  @next=VH ;
  d':de      ADP    Host  @next=VH ;
  j':je      PRO    Host  @next=VH ;
  n':ne      ADV    Host  @next=VH ;
  m':me      PRO    Host  @next=VH ;
  t':te      PRO    Host  @next=VH ;
  s':se      PRO    Host  @next=VH ;
  c':ce      PRO    Host  @next=VH ;
  qu':que    CONJ   Host  @next=VH ;
  jusqu':jusque  ADP  Host  @next=VH ;
  lorsqu':lorsque  CONJ  Host  @next=VH ;
  puisqu':puisque  CONJ  Host  @next=VH ;
";

/// Context rules learned by `cargo run --release --example treebank --
/// learn` on UD French GSD train, stopped on dev. The first that applies
/// decides; they are plain spec text, never weighted.
const RULES: &str = "\
PREFER DET OVER PRO BEFORE N
PREFER V OVER N AFTER N
PREFER V AFTER PRO
PREFER V OVER N AFTER V
PREFER ADP BEFORE DET
PREFER N AFTER DET
PREFER V OVER N AFTER ADV
PREFER V OVER N AFTER NAME
PREFER ADV BEFORE ADP
PREFER DET OVER PRO BEFORE ADJ
PREFER ADP AFTER N
PREFER ADP AFTER V
PREFER V OVER N AFTER PUNCT
PREFER DET OVER PRO BEFORE NAME
";

/// Verbs whose stems change too much to split (est, suis, sont; ai, eu;
/// va, irai; fait, fis): their forms are listed whole, ahead of the
/// generated lexicons.
const SUPPLETIVE: [&str; 4] = ["être", "avoir", "aller", "faire"];

/// UniMorph rows for the generator, and whole-form entries for the
/// suppletive verbs.
fn to_unimorph(lexicon: &str) -> (String, String) {
    let mut rows = BTreeSet::new();
    let mut whole = BTreeSet::new();
    for line in lexicon.lines() {
        let c: Vec<&str> = line.split('\t').collect();
        let (Some(form), Some(lemma), Some(tags)) = (c.get(2), c.get(3), c.get(4)) else { continue };
        if c.first().is_none_or(|id| !id.chars().all(|ch| ch.is_ascii_digit()) || id.is_empty()) {
            continue;
        }
        // single words only, no digits, no proper names (capitalized)
        let word = |s: &str| !s.is_empty() && s.chars().all(|ch| ch.is_alphabetic() || ch == '-' || ch == '\'') && !s.starts_with(char::is_uppercase);
        if !word(form) || !word(lemma) {
            continue;
        }
        let tags: Vec<&str> = tags.split_whitespace().collect();
        for f in features(&tags) {
            if f.starts_with('V') && SUPPLETIVE.contains(lemma) {
                whole.insert(format!("  {form}:{lemma}  {f}  # ;\n"));
            } else {
                rows.insert(format!("{lemma}\t{form}\t{f}\n"));
            }
        }
    }
    (rows.into_iter().collect(), whole.into_iter().collect())
}

fn main() -> ExitCode {
    let Some(path) = std::env::args().nth(1) else {
        eprintln!("usage: build_french <lexique-grammalecte-fr-v7.7.txt> > data/french.morph");
        return ExitCode::FAILURE;
    };
    let run = || -> Result<String, Box<dyn std::error::Error>> {
        let (tsv, whole) = to_unimorph(&std::fs::read_to_string(&path)?);
        let g = morph_fst::generate::from_unimorph(&tsv)?;
        eprintln!("{} lemmas, {} forms, {} paradigms, {} irregular", g.lemmas, g.forms, g.paradigms, g.irregular);
        if !g.spec.contains("\nLEXICON Root\n") {
            return Err("generated spec has no LEXICON Root".into());
        }
        let words = g.spec.replacen("\nLEXICON Root\n", "\nLEXICON Words\n", 1);
        let spec = format!("{HEADER}{CLITICS}\nLEXICON Suppletive\n{whole}\n{words}\n! context rules (see examples/build_french.rs)\n{RULES}");
        morph_fst::Lexer::compile(&spec)?;
        Ok(spec)
    };
    match run() {
        Ok(spec) => {
            print!("{spec}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("build_french: {e}");
            ExitCode::FAILURE
        }
    }
}
