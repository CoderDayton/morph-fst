//! Build `data/korean.morph` from the hand-written grammar in
//! `tools/korean/grammar.morph` and mecab-ko-dic
//! (<https://bitbucket.org/eunjeon/mecab-ko-dic>, Apache-2.0).
//!
//! ```sh
//! curl -LO https://bitbucket.org/eunjeon/mecab-ko-dic/downloads/mecab-ko-dic-2.1.1-20180720.tar.gz
//! tar xzf mecab-ko-dic-2.1.1-20180720.tar.gz
//! cargo run --release --example build_korean -- mecab-ko-dic-2.1.1-20180720 > data/korean.morph
//! ```
//!
//! mecab-ko-dic lists stems, particles and endings by part of speech
//! (`surface,left,right,cost,POS,...`; the ids and costs are unused), and
//! in `Inflect.csv` the irregular forms with their analysis (`가까운` =
//! `가깝/VV + 은/ETM`). Stems take the grammar's flags: 하 → `@ha`,
//! 오 → `@wa`, other open ㅗ → `@wa_opt`, 르 → `@reu`, and ㅂ/ㄷ stems whose
//! listed forms show the change (추워, 들어) → `@b`/`@d`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::process::ExitCode;

const GRAMMAR: &str = include_str!("../tools/korean/grammar.morph");

const HEADER: &str = "\
! =====================================================================
!  GENERATED by examples/build_korean.rs: do not edit by hand.
!  Edit tools/korean/grammar.morph and regenerate.
!
!  The lexicon is derived from mecab-ko-dic
!  (https://bitbucket.org/eunjeon/mecab-ko-dic) by Yongwoon Lee and
!  Yungho Yu, licensed under the Apache License, Version 2.0. The notice
!  is in data/korean-MECAB-KO-DIC-LICENSE.txt.
! =====================================================================

";

/// A Hangul syllable as conjoining jamo; other characters unchanged.
fn jamo(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        let u = c as u32;
        if (0xAC00..0xAC00 + 11172).contains(&u) {
            let i = u - 0xAC00;
            out.extend(char::from_u32(0x1100 + i / 588));
            out.extend(char::from_u32(0x1161 + (i % 588) / 28));
            if i % 28 != 0 {
                out.extend(char::from_u32(0x11A7 + i % 28));
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// A leading compatibility consonant (ㄴ in `ㄴ가`) as the final jamo it
/// stands for; `None` if other compatibility jamo remain.
fn ending_surface(s: &str) -> Option<String> {
    const COMPAT: [(char, char); 6] = [('ㄱ', 'ᆨ'), ('ㄴ', 'ᆫ'), ('ㄹ', 'ᆯ'), ('ㅁ', 'ᆷ'), ('ㅂ', 'ᆸ'), ('ㅆ', 'ᆻ')];
    let mut cs = s.chars();
    let first = cs.next()?;
    let lead = COMPAT.iter().find(|(c, _)| *c == first).map(|(_, f)| *f);
    let rest: String = if lead.is_some() { cs.collect() } else { s.to_string() };
    let ok = |c: char| ('\u{AC00}'..='\u{D7A3}').contains(&c) || ('\u{1100}'..='\u{11FF}').contains(&c);
    if !rest.chars().all(ok) || (lead.is_none() && rest.is_empty()) {
        return None;
    }
    Some(lead.map(String::from).unwrap_or_default() + &rest)
}

fn hangul(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| ('\u{AC00}'..='\u{D7A3}').contains(&c))
}

struct Row {
    surface: String,
    pos: String,
    expr: String,
}

fn read_csv(dir: &str, file: &str) -> Result<Vec<Row>, String> {
    let text = std::fs::read_to_string(format!("{dir}/{file}")).map_err(|e| format!("{file}: {e}"))?;
    Ok(text
        .lines()
        .filter_map(|l| {
            let c: Vec<&str> = l.split(',').collect();
            Some(Row { surface: c.first()?.to_string(), pos: c.get(4)?.to_string(), expr: c.get(11).unwrap_or(&"*").to_string() })
        })
        .collect())
}

/// The irregular stem flag of `stem`, from the forms of it Inflect.csv
/// lists (jamo): ㅂ→우 (추워), ㄷ→ㄹ before a vowel (들어).
fn irregular_flag(stem: &str, forms: &[String]) -> &'static str {
    let j = jamo(stem);
    if let Some(base) = j.strip_suffix('ᆸ') {
        let alt = format!("{base}우");
        let alt2 = format!("{base}워");
        if forms.iter().any(|f| f.starts_with(&alt) || f.starts_with(&alt2)) {
            return " @b";
        }
    }
    if let Some(base) = j.strip_suffix('ᆮ') {
        let alt = format!("{base}ᆯᄋ");
        if forms.iter().any(|f| f.starts_with(&alt)) {
            return " @d @set:bat=C";
        }
    }
    ""
}

/// Flags of a verb or adjective stem.
fn flags(stem: &str, forms: &[String]) -> String {
    let last = stem.chars().last().unwrap_or(' ');
    let mut f = String::new();
    if last == '하' {
        f.push_str(" @ha");
    } else if last == '오' {
        f.push_str(" @wa");
    } else if jamo(&last.to_string()).ends_with('ᅩ') {
        f.push_str(" @wa_opt");
    } else if last == '르' && !["따르", "치르", "들르", "우러르", "이르", "푸르", "누르"].iter().any(|s| stem.ends_with(s)) {
        f.push_str(" @reu");
    }
    f.push_str(irregular_flag(stem, forms));
    f
}

fn build(dir: &str) -> Result<String, Box<dyn std::error::Error>> {
    let mut lex: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();
    let mut add = |name: &'static str, line: String| {
        lex.entry(name).or_default().insert(line);
    };
    // irregular forms: whole, under their stem
    let inflect = read_csv(dir, "Inflect.csv")?;
    let mut forms_of: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for r in &inflect {
        let morphs: Vec<(&str, &str)> = r.expr.split('+').filter_map(|m| m.split_once('/').map(|(s, rest)| (s, rest.split('/').next().unwrap_or("")))).collect();
        let Some(&(stem, first)) = morphs.first() else { continue };
        let class = match first {
            "VV" | "VX" => "V",
            "VA" => "ADJ",
            _ => continue,
        };
        if !hangul(&r.surface) || !hangul(stem) || morphs.len() < 2 {
            continue;
        }
        forms_of.entry(stem.to_string()).or_default().push(jamo(&r.surface));
        let rest: Vec<&str> = morphs[1..].iter().map(|(_, p)| *p).collect();
        let next = if rest.last() == Some(&"ETN") { "Particles" } else { "#" };
        add("Inflected", format!("  {}:{stem}  {class};{}  {next} ;", r.surface, rest.join(".")));
    }
    let none = Vec::new();
    for (file, class) in [("VV.csv", "V"), ("VX.csv", "V"), ("VA.csv", "ADJ")] {
        let lexicon = if class == "ADJ" { "Adjs @open=ADJ" } else { "Verbs @open=V" };
        for r in read_csv(dir, file)? {
            if hangul(&r.surface) && r.expr == "*" {
                let f = flags(&r.surface, forms_of.get(&r.surface).unwrap_or(&none));
                add(lexicon, format!("  {}  {class}  VStem{f} ;", r.surface));
            }
        }
    }
    for file in ["NNG.csv", "NNB.csv", "NNP.csv", "NNBC.csv"] {
        for r in read_csv(dir, file)? {
            if hangul(&r.surface) {
                add("Nouns @open=N", format!("  {}  N  NounCont ;", r.surface));
            }
        }
    }
    for (file, tag, next) in [
        ("NP.csv", "PRON", "Particles"),
        ("NR.csv", "NUM", "Particles"),
        ("MAG.csv", "ADV", "Aux"),
        ("MAJ.csv", "CONJ", "#"),
        ("MM.csv", "DET", "#"),
        ("IC.csv", "INTJ", "#"),
    ] {
        for r in read_csv(dir, file)? {
            if hangul(&r.surface) {
                add("Words", format!("  {}  {tag}  {next} ;", r.surface));
            }
        }
    }
    for r in read_csv(dir, "J.csv")? {
        if let Some(s) = ending_surface(&r.surface) {
            add("MParticles", format!("  {s}  {}  Aux ;", r.pos));
        }
    }
    for (file, lexicon, next) in [
        ("EP.csv", "MPrefinal", "MEndings"),
        ("EC.csv", "MEndings", "#"),
        ("EF.csv", "MEndings", "#"),
        ("ETM.csv", "MEndings", "#"),
        ("ETN.csv", "MEndings", "Particles"),
    ] {
        for r in read_csv(dir, file)? {
            if let (Some(s), true) = (ending_surface(&r.surface), r.expr == "*") {
                add(lexicon, format!("  {s}  {}  {next} ;", r.pos));
            }
        }
    }
    let mut generated = String::new();
    for (name, lines) in &lex {
        writeln!(generated, "LEXICON {name}")?;
        for l in lines {
            writeln!(generated, "{l}")?;
        }
        generated.push('\n');
        eprintln!("{name}: {}", lines.len());
    }
    if !GRAMMAR.contains("!@GENERATED\n") {
        return Err("grammar has no !@GENERATED marker".into());
    }
    let spec = format!("{HEADER}{}", GRAMMAR.replacen("!@GENERATED\n", &generated, 1));
    let lx = morph_fst::Lexer::compile(&spec)?;
    eprintln!("compiled: {} entries", lx.mt.entries.len());
    Ok(spec)
}

fn main() -> ExitCode {
    let Some(dir) = std::env::args().nth(1) else {
        eprintln!("usage: build_korean <mecab-ko-dic-2.1.1-20180720> > data/korean.morph");
        return ExitCode::FAILURE;
    };
    match build(&dir) {
        Ok(spec) => {
            print!("{spec}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("build_korean: {e}");
            ExitCode::FAILURE
        }
    }
}
