//! Build `data/spanish.morph` from the RLA-ES Hunspell dictionary
//! (<https://github.com/sbosio/rla-es>, GPL-3 / LGPL-3 / MPL-1.1; used
//! under the MPL-1.1) and the function words of
//! `tools/spanish/closed.morph`.
//!
//! ```sh
//! B=https://raw.githubusercontent.com/LibreOffice/dictionaries/master/es
//! curl -LO $B/es_ES.aff -LO $B/es_ES.dic
//! cargo run --release --example build_spanish -- es_ES.aff es_ES.dic > data/spanish.morph
//! ```
//!
//! Hunspell spells every form but names no features. The affix flags say
//! the word class (conjugation flags: verb; gender: adjective; plural
//! alone: noun), and the regular endings of the three conjugations give a
//! verb form its features. Derivation and prefix classes are left out:
//! Hunspell would give `acción` the lemma `accionar`.

use std::collections::{BTreeMap, BTreeSet};
use std::process::ExitCode;

const CLOSED: &str = include_str!("../tools/spanish/closed.morph");
const IRREGULAR: &str = include_str!("../tools/spanish/irregular.txt");

/// The features of each slot of a line of `irregular.txt`, group by group.
const SLOTS: [&[&str]; 8] = [
    &["NFIN", "V.CVB;PRS", "V.PTCP;PST"],
    &["IND;PRS;1;SG", "IND;PRS;2;SG", "IND;PRS;3;SG", "IND;PRS;1;PL", "IND;PRS;2;PL", "IND;PRS;3;PL"],
    &["IND;PST;PFV;1;SG", "IND;PST;PFV;2;SG", "IND;PST;PFV;3;SG", "IND;PST;PFV;1;PL", "IND;PST;PFV;2;PL", "IND;PST;PFV;3;PL"],
    &["IND;PST;IPFV;1;SG", "IND;PST;IPFV;2;SG", "IND;PST;IPFV;3;SG", "IND;PST;IPFV;1;PL", "IND;PST;IPFV;2;PL", "IND;PST;IPFV;3;PL"],
    &["IND;FUT;1;SG", "IND;FUT;2;SG", "IND;FUT;3;SG", "IND;FUT;1;PL", "IND;FUT;2;PL", "IND;FUT;3;PL"],
    &["COND;1;SG", "COND;2;SG", "COND;3;SG", "COND;1;PL", "COND;2;PL", "COND;3;PL"],
    &["SBJV;PRS;1;SG", "SBJV;PRS;2;SG", "SBJV;PRS;3;SG", "SBJV;PRS;1;PL", "SBJV;PRS;2;PL", "SBJV;PRS;3;PL"],
    &["SBJV;PST;1;SG", "SBJV;PST;2;SG", "SBJV;PST;3;SG", "SBJV;PST;1;PL", "SBJV;PST;2;PL", "SBJV;PST;3;PL"],
];

/// `LEXICON Irregular` from `irregular.txt`, in the table's order (among
/// equal readings the earlier entry wins: `fue` is ser before ir), and the
/// verbs it covers.
fn irregular(table: &str) -> Result<(String, BTreeSet<&str>), String> {
    let mut lines: Vec<String> = Vec::new();
    let mut verbs = BTreeSet::new();
    for (n, line) in table.lines().enumerate().filter(|(_, l)| !l.trim().is_empty() && !l.starts_with('#')) {
        let groups: Vec<Vec<&str>> = line.split('|').map(|g| g.split_whitespace().collect()).collect();
        let lemma = *groups.first().and_then(|g| g.first()).ok_or(format!("irregular.txt line {}: empty", n + 1))?;
        if groups.len() != SLOTS.len() || groups.iter().zip(SLOTS).any(|(g, s)| g.len() != s.len()) {
            return Err(format!("irregular.txt line {}: expected 3 | 6 x 7 forms", n + 1));
        }
        verbs.insert(lemma);
        for (forms, feats) in groups.iter().zip(SLOTS) {
            for (form, f) in forms.iter().zip(feats) {
                let line = format!("  {form}:{lemma}  V;{f}  # ;\n");
                if !lines.contains(&line) {
                    lines.push(line);
                }
            }
        }
    }
    lines.push("  hay:haber  V;IND;PRS;3;SG  # ;\n".into());
    Ok((format!("LEXICON Irregular\n{}", lines.concat()), verbs))
}

