/// Affix classes that inflect: conjugation (R E I X), participles (D),
/// gender (G), plural (S) and the enclitic pronouns (accented flags).
fn inflectional(class: &str) -> bool {
    let Some(flag) = class.strip_prefix("SFX_") else { return false };
    matches!(flag, "R" | "E" | "I" | "X" | "D" | "G" | "S") || flag.chars().next().is_some_and(|c| ('\u{C0}'..='\u{FF}').contains(&c))
}

