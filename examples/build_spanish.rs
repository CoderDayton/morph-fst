/// Features of a regular verb form, or `V` alone when the form is not
/// stem + regular ending (irregular forms, enclitic pronouns).
fn verb_features(lemma: &str, form: &str) -> Vec<String> {
    let (stem, conj) = match lemma.len().checked_sub(2).and_then(|i| lemma.get(i..).map(|e| (&lemma[..i], e))) {
        Some((s, "ar")) => (s, 0),
        Some((s, "er")) => (s, 1),
        Some((s, "ir")) => (s, 2),
        _ => return vec!["V".into()],
    };
    let mut out = Vec::new();
    if let Some(rest) = form.strip_prefix(lemma) {
        out.extend(FUT.iter().filter(|(e, _)| *e == rest).flat_map(|(_, f)| f.split('|')).map(|f| format!("V;{f}")));
    }
    if let Some(rest) = form.strip_prefix(stem) {
        // participles inflect for gender and number
        let ptcp = if conj == 0 { "ad" } else { "id" };
        if let Some(gn) = rest.strip_prefix(ptcp) {
            let feats = match gn {
                "o" => Some("MASC;SG"),
                "a" => Some("FEM;SG"),
                "os" => Some("MASC;PL"),
                "as" => Some("FEM;PL"),
                _ => None,
            };
            out.extend(feats.map(|g| format!("V.PTCP;PST;{g}")));
        }
        let tables: &[&[(&str, &str)]] = match conj {
            0 => &[AR],
            1 => &[ER, ER_IR],
            _ => &[IR, ER_IR],
        };
        for t in tables {
            out.extend(t.iter().filter(|(e, _)| *e == rest).flat_map(|(_, f)| f.split('|')).map(|f| format!("V;{f}")));
        }
    }
    if out.is_empty() {
        out.push("V".into());
    }
    out
}

/// Gender and number of a noun or adjective form.
fn nominal_features(pos: &str, lemma: &str, form: &str) -> String {
    let plural = form != lemma && form.ends_with('s');
    let gender = match (pos, form.trim_end_matches('s').chars().last()) {
        ("ADJ", Some('o')) => ";MASC",
        ("ADJ", Some('a')) if lemma.ends_with('o') => ";FEM",
        _ => "",
    };
    format!("{pos}{gender};{}", if plural { "PL" } else { "SG" })
}

/// UniMorph rows with word classes and features, from the dictionary's
/// expanded rows (`lemma<TAB>form<TAB>STEM;SFX_x`).
fn label(expanded: &str, closed: &BTreeSet<&str>, irregular: &BTreeSet<&str>, listed: &BTreeSet<String>) -> String {
    // the classes each lemma's forms use
    let mut flags: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    let mut forms: Vec<(&str, &str, Option<&str>)> = Vec::new();
    for line in expanded.lines() {
        let mut c = line.split('\t');
        let (Some(lemma), Some(form), Some(feats)) = (c.next(), c.next(), c.next()) else { continue };
        let class = feats.split(';').nth(1);
        // bare entries of irregular forms (es, ha, fue) are the hand table's
        let bare_irregular = class.is_none() && listed.contains(form);
        if class.is_some_and(|k| !inflectional(k)) || lemma.starts_with(char::is_uppercase) || closed.contains(form) || irregular.contains(lemma) || bare_irregular {
            continue;
        }
        flags.entry(lemma).or_default().extend(class);
        forms.push((lemma, form, class));
    }
    let mut rows = BTreeSet::new();
    for (lemma, form, _) in forms {
        let f = flags.get(lemma).cloned().unwrap_or_default();
        let has = |k: &str| f.contains(k);
        let verb = ["SFX_R", "SFX_E", "SFX_I", "SFX_X"].iter().any(|k| has(k)) && ["ar", "er", "ir"].iter().any(|e| lemma.ends_with(e));
        let feats = if verb {
            verb_features(lemma, form)
        } else if has("SFX_G") {
            vec![nominal_features("ADJ", lemma, form)]
        } else if lemma.ends_with("mente") && f.is_empty() {
            vec!["ADV".into()]
        } else {
            vec![nominal_features("N", lemma, form)]
        };
        for x in feats {
            rows.insert(format!("{lemma}\t{form}\t{x}\n"));
        }
    }
    rows.into_iter().collect()
}

/// The surfaces the hand-written closed lexicon lists.
fn closed_words(spec: &str) -> BTreeSet<&str> {
    spec.lines()
        .filter_map(|l| l.split('!').next())
        .filter(|l| l.starts_with("  "))
        .filter_map(|l| l.split_whitespace().next())
        .map(|w| w.split(':').next().unwrap_or(w))
        .collect()
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [aff, dic] = args.as_slice() else {
        eprintln!("usage: build_spanish <es_ES.aff> <es_ES.dic> > data/spanish.morph");
        return ExitCode::FAILURE;
    };
    let run = || -> Result<String, Box<dyn std::error::Error>> {
        let expanded = morph_fst::hunspell::to_unimorph(&std::fs::read_to_string(aff)?, &std::fs::read_to_string(dic)?)?;
        let (irr, verbs) = irregular(IRREGULAR)?;
        let listed: BTreeSet<String> = irr.lines().skip(1).filter_map(|l| l.split_whitespace().next()).filter_map(|w| w.split(':').next()).map(str::to_string).collect();
        let tsv = label(&expanded, &closed_words(CLOSED), &verbs, &listed);
        let g = morph_fst::generate::from_unimorph(&tsv)?;
        eprintln!("{} lemmas, {} forms, {} paradigms, {} irregular", g.lemmas, g.forms, g.paradigms, g.irregular);
        if !g.spec.contains("\nLEXICON Root\n") || !CLOSED.contains("!@GENERATED\n") {
            return Err("generated spec has no LEXICON Root, or closed.morph no !@GENERATED marker".into());
        }
        let words = g.spec.replacen("\nLEXICON Root\n", "\nLEXICON Words\n", 1);
        let spec = format!("{HEADER}{}", CLOSED.replacen("!@GENERATED\n", &format!("{irr}\n{words}"), 1));
        morph_fst::Lexer::compile(&spec)?;
        Ok(spec)
    };
    match run() {
        Ok(spec) => {
            print!("{spec}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("build_spanish: {e}");
            ExitCode::FAILURE
        }
    }
}
