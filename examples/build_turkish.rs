//! Build `data/turkish.morph` from the hand-written grammar in
//! `tools/turkish/grammar.morph` and the Zemberek-NLP lexicon
//! (<https://github.com/ahmetaa/zemberek-nlp>, Apache-2.0).
//!
//! ```sh
//! git clone --depth 1 https://github.com/ahmetaa/zemberek-nlp
//! cargo run --release --example build_turkish -- zemberek-nlp/morphology/src/main/resources/tr > data/turkish.morph
//! ```
//!
//! Each Zemberek line is `word [P:pos; A:attributes; ...]`. With no `P:`,
//! a word ending in `-mak`/`-mek` is a verb and anything else a noun. The
//! attributes become the grammar's flags: voicing → `@soft`, last vowel
//! drop → `@drop`, doubling → `@dbl`, inverse harmony → `@set:vow=..`,
//! and the aorist vowel picks the verb's continuation.

use std::collections::BTreeSet;
use std::fmt::Write;
use std::process::ExitCode;

const GRAMMAR: &str = include_str!("../tools/turkish/grammar.morph");
const FILES: [&str; 2] = ["master-dictionary.dict", "non-tdk.dict"];
const LETTERS: &str = "abcçdefgğhıijklmnoöprsştuüvyzâîûqwx";
const VOWELS: &str = "aeıioöuüâîû";

const HEADER: &str = "\
! =====================================================================
!  GENERATED by examples/build_turkish.rs: do not edit by hand.
!  Edit tools/turkish/grammar.morph and regenerate.
!
!  The lexicon is derived from Zemberek-NLP
!  (https://github.com/ahmetaa/zemberek-nlp), Copyright 2018 Ahmet A.
!  Akın, Mehmet D. Akın, licensed under the Apache License, Version 2.0.
!  The notice is in data/turkish-ZEMBEREK-LICENSE.txt.
! =====================================================================

";

struct Entry {
    word: String,
    pos: String,
    attrs: Vec<String>,
    /// Zemberek gives a pronunciation (`tv [Pr:tivi]`): harmony follows
    /// the sound, not the spelling, which the grammar cannot see.
    spoken: bool,
}

fn parse(line: &str) -> Option<Entry> {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let (word, meta) = match line.split_once('[') {
        Some((w, m)) => (w.trim(), m.trim_end_matches(']')),
        None => (line, ""),
    };
    let mut e = Entry { word: word.to_string(), pos: String::new(), attrs: Vec::new(), spoken: false };
    for field in meta.split(';') {
        let Some((key, value)) = field.split_once(':') else { continue };
        let mut values = value.split(',').map(|s| s.trim().to_string());
        match key.trim() {
            "P" => e.pos = values.next().unwrap_or_default(),
            "A" => e.attrs.extend(values),
            "Pr" => e.spoken = true,
            _ => {}
        }
    }
    Some(e)
}

/// The lexicon an entry goes to and its line, or `None` to leave it out.
fn place(e: &Entry, closed: &BTreeSet<&str>) -> Option<(usize, String)> {
    let w = e.word.as_str();
    if e.spoken || w.is_empty() || !w.chars().all(|c| LETTERS.contains(c)) {
        return None;
    }
    let has = |a: &str| e.attrs.iter().any(|x| x == a);
    let pos = match e.pos.as_str() {
        "" if w.ends_with("mak") || w.ends_with("mek") => "Verb",
        "" => "Noun",
        p => p,
    };
    let tag = match pos {
        "Noun" => "N",
        "Adj" => "ADJ",
        "Verb" => "V",
        "Adv" => "ADV",
        "Conj" => "CONJ",
        "Pron" => "PRON",
        "Det" => "DET",
        "Postp" => "POSTP",
        "Interj" => "INTERJ",
        "Num" => "NUM",
        "Ques" => "QUES",
        _ => return None,
    };
    let mut flags = String::new();
    match tag {
        "N" | "ADJ" => {
            // Zemberek voices a final p ç t k by default in words of more
            // than one syllable; `Voicing` and `NoVoicing` override it.
            let syllables = w.chars().filter(|c| VOWELS.contains(*c)).count();
            let stop = w.chars().last().is_some_and(|c| "pçtk".contains(c));
            if stop && (has("Voicing") || (syllables > 1 && !has("NoVoicing"))) {
                flags.push_str(" @soft");
            }
            if has("LastVowelDrop") {
                flags.push_str(" @drop");
            }
            if has("Doubling") {
                flags.push_str(" @dbl");
            }
            if has("InverseHarmony") {
                let rounded = w.chars().rev().find(|c| VOWELS.contains(*c)).is_some_and(|c| "oöuüû".contains(c));
                flags.push_str(if rounded { " @set:vow=fr" } else { " @set:vow=fu" });
            }
            Some((usize::from(tag == "ADJ"), format!("  {w}  {tag}  NounCont{flags} ;")))
        }
        "V" => {
            let stem = w.strip_suffix("mak").or_else(|| w.strip_suffix("mek")).filter(|s| !s.is_empty())?;
            if has("Voicing") {
                flags.push_str(" @soft");
            }
            // Zemberek: a one-syllable stem takes the -Ar aorist (yap-ar),
            // a longer one -Ir (getir-ir); `Aorist_A`/`Aorist_I` override.
            let syllables = stem.chars().filter(|c| VOWELS.contains(*c)).count();
            let cont = if has("Aorist_A") || (!has("Aorist_I") && syllables == 1) { "VerbContA" } else { "VerbCont" };
            Some((2, format!("  {stem}  V  {cont}{flags} ;")))
        }
        _ if closed.contains(w) => None,
        _ => Some((3, format!("  {w}  {tag}  # ;"))),
    }
}

/// The surfaces the grammar's own `LEXICON Closed` lists.
fn closed_words(grammar: &str) -> BTreeSet<&str> {
    let section = grammar.split("LEXICON Closed").nth(1).unwrap_or("");
    let section = section.split("LEXICON ").next().unwrap_or("");
    section.lines().filter_map(|l| l.split('!').next()).filter_map(|l| l.split_whitespace().next()).collect()
}

fn build(dicts: &[String]) -> Result<String, Box<dyn std::error::Error>> {
    const NAMES: [&str; 4] = ["Nouns @open=N", "Adjs @open=ADJ", "Verbs @open=V", "Words"];
    let closed = closed_words(GRAMMAR);
    let mut lexicons: [BTreeSet<String>; 4] = Default::default();
    for text in dicts {
        for (i, line) in text.lines().filter_map(parse).filter_map(|e| place(&e, &closed)) {
            lexicons[i].insert(line);
        }
    }
    let mut generated = String::new();
    for (name, lines) in NAMES.iter().zip(&lexicons) {
        writeln!(generated, "LEXICON {name}")?;
        for l in lines {
            writeln!(generated, "{l}")?;
        }
        generated.push('\n');
        eprintln!("{name}: {}", lines.len());
    }
    if !GRAMMAR.contains("!@GENERATED\n") {
        return Err("grammar has no !@GENERATED marker".into());
    }
    let spec = format!("{HEADER}{}", GRAMMAR.replacen("!@GENERATED\n", &generated, 1));
    let lx = morph_fst::Lexer::compile(&spec)?;
    eprintln!("compiled: {} entries", lx.mt.entries.len());
    Ok(spec)
}

fn main() -> ExitCode {
    let Some(dir) = std::env::args().nth(1) else {
        eprintln!("usage: build_turkish <zemberek-nlp/morphology/src/main/resources/tr> > data/turkish.morph");
        return ExitCode::FAILURE;
    };
    let dicts: Result<Vec<String>, _> = FILES.iter().map(|f| std::fs::read_to_string(format!("{dir}/{f}"))).collect();
    match dicts.map_err(Into::into).and_then(|d| build(&d)) {
        Ok(spec) => {
            print!("{spec}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("build_turkish: {e}");
            ExitCode::FAILURE
        }
    }
}
